/*
 * KernelWatch collector daemon.
 *
 * Loads the BPF programs in collector.bpf.c, attaches a ring buffer
 * consumer, and converts each kernel-side struct event into a CDM20-shaped
 * JSONL record (RECORD_SUBJECT / RECORD_OBJECT / RECORD_EVENT), so it can
 * be fed straight into the same graph-building code used for the DARPA TC
 * data.
 *
 * Build: see Makefile. Requires libbpf-dev, bpftool, clang.
 * Run:   sudo ./collector [-o output.jsonl]
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <signal.h>
#include <unistd.h>
#include <time.h>
#include <arpa/inet.h>
#include <bpf/libbpf.h>

#include "../include/collector.h"
#include "collector.skel.h"   /* generated by bpftool gen skeleton */

static volatile sig_atomic_t running = 1;
static FILE *out = NULL;

static void handle_sigint(int sig)
{
    (void)sig;
    running = 0;
}

/* ---------------------------------------------------------------------
 * UUID synthesis — deterministic 64-bit hashes standing in for CDM's
 * UUIDs. FNV-1a is enough here; collisions matter far less than
 * *consistency* (same pid+start_ns always yields the same subject uuid).
 * ------------------------------------------------------------------- */
static uint64_t fnv1a(const void *data, size_t len)
{
    const uint8_t *p = data;
    uint64_t h = 1469598103934665603ULL;
    for (size_t i = 0; i < len; i++) {
        h ^= p[i];
        h *= 1099511628211ULL;
    }
    return h;
}

static uint64_t subject_uuid(uint32_t pid, uint64_t start_ns)
{
    struct { uint32_t pid; uint64_t start_ns; } key = { pid, start_ns };
    return fnv1a(&key, sizeof(key));
}

static uint64_t net_uuid(uint32_t saddr, uint32_t daddr,
                          uint16_t sport, uint16_t dport, uint8_t proto)
{
    struct { uint32_t s, d; uint16_t sp, dp; uint8_t p; } __attribute__((packed)) key =
        { saddr, daddr, sport, dport, proto };
    return fnv1a(&key, sizeof(key));
}

static uint64_t file_uuid(const char *path)
{
    return fnv1a(path, strlen(path));
}

/* pid -> start_ns cache so repeated events from the same process reuse the
 * same subject uuid. Simple fixed-size linear table; swap for a hashmap if
 * you're running this against a busy multi-tenant host. */
#define PID_CACHE_SIZE 8192
struct pid_entry { uint32_t pid; uint64_t start_ns; int used; };
static struct pid_entry pid_cache[PID_CACHE_SIZE];

static uint64_t start_ns_for(uint32_t pid, uint64_t now_ns, int is_new)
{
    struct pid_entry *slot = &pid_cache[pid % PID_CACHE_SIZE];
    if (is_new || !slot->used || slot->pid != pid) {
        slot->pid = pid;
        slot->start_ns = now_ns;
        slot->used = 1;
    }
    return slot->start_ns;
}

static const char *event_type_name(uint32_t t)
{
    switch (t) {
    case EVENT_EXECUTE:          return "EVENT_EXECUTE";
    case EVENT_CLONE:            return "EVENT_CLONE";
    case EVENT_EXIT:              return "EVENT_EXIT";
    case EVENT_OPEN:              return "EVENT_OPEN";
    case EVENT_READ:              return "EVENT_READ";
    case EVENT_WRITE:             return "EVENT_WRITE";
    case EVENT_MMAP:              return "EVENT_MMAP";
    case EVENT_MPROTECT:          return "EVENT_MPROTECT";
    case EVENT_CONNECT:           return "EVENT_CONNECT";
    case EVENT_SENDTO:            return "EVENT_SENDTO";
    case EVENT_RECVFROM:          return "EVENT_RECVFROM";
    case EVENT_CHANGE_PRINCIPAL:  return "EVENT_CHANGE_PRINCIPAL";
    case EVENT_UNLINK:            return "EVENT_UNLINK";
    case EVENT_INJECT_PTRACE:     return "EVENT_INJECT_PTRACE";
    case EVENT_INJECT_VM_WRITE:   return "EVENT_INJECT_VM_WRITE";
    default:                      return "EVENT_UNKNOWN";
    }
}

/* ---------------------------------------------------------------------
 * Ring buffer callback — one struct event in, one JSONL line out.
 * ------------------------------------------------------------------- */
static int handle_event(void *ctx, void *data, size_t data_sz)
{
    (void)ctx;
    if (data_sz < sizeof(struct event))
        return 0;

    const struct event *e = data;

    int is_new = (e->event_type == EVENT_EXECUTE);
    uint64_t start_ns = start_ns_for(e->pid, e->timestamp_ns, is_new);
    uint64_t subj = subject_uuid(e->pid, start_ns);

    /* RECORD_SUBJECT — emitted on every event so a consumer can build the
     * process table incrementally without a separate exec-only stream. */
    fprintf(out,
        "{\"type\":\"RECORD_SUBJECT\",\"uuid\":\"%016llx\",\"pid\":%u,"
        "\"ppid\":%u,\"tid\":%u,\"uid\":%u,\"euid\":%u,\"gid\":%u,"
        "\"egid\":%u,\"comm\":\"%s\",\"start_ns\":%llu}\n",
        (unsigned long long)subj, e->pid, e->ppid, e->tid,
        e->uid, e->euid, e->gid, e->egid, e->comm,
        (unsigned long long)start_ns);

    /* RECORD_EVENT — the typed edge, shaped close to CDM's Event record */
    fprintf(out,
        "{\"type\":\"RECORD_EVENT\",\"event_type\":\"%s\","
        "\"timestampNanos\":%llu,\"subject_uuid\":\"%016llx\"",
        event_type_name(e->event_type),
        (unsigned long long)e->timestamp_ns,
        (unsigned long long)subj);

    switch (e->event_type) {
    case EVENT_CONNECT:
    case EVENT_SENDTO:
    case EVENT_RECVFROM: {
        char saddr[INET_ADDRSTRLEN], daddr[INET_ADDRSTRLEN];
        struct in_addr sa = { .s_addr = e->data.net.saddr };
        struct in_addr da = { .s_addr = e->data.net.daddr };
        inet_ntop(AF_INET, &sa, saddr, sizeof(saddr));
        inet_ntop(AF_INET, &da, daddr, sizeof(daddr));
        uint64_t obj = net_uuid(e->data.net.saddr, e->data.net.daddr,
                                 e->data.net.sport, e->data.net.dport,
                                 e->data.net.protocol);
        fprintf(out,
            ",\"object_uuid\":\"%016llx\",\"object_type\":\"NetFlowObject\","
            "\"localAddress\":\"%s\",\"localPort\":%u,"
            "\"remoteAddress\":\"%s\",\"remotePort\":%u",
            (unsigned long long)obj, saddr, e->data.net.sport,
            daddr, e->data.net.dport);
        break;
    }
    case EVENT_OPEN:
    case EVENT_UNLINK: {
        uint64_t obj = file_uuid(e->data.file.path);
        fprintf(out,
            ",\"object_uuid\":\"%016llx\",\"object_type\":\"FileObject\","
            "\"path\":\"%s\"",
            (unsigned long long)obj, e->data.file.path);
        break;
    }
    case EVENT_MPROTECT:
        fprintf(out,
            ",\"addr\":%llu,\"len\":%llu,\"prot\":%u",
            (unsigned long long)e->data.mem.addr,
            (unsigned long long)e->data.mem.len,
            e->data.mem.prot);
        break;
    case EVENT_CHANGE_PRINCIPAL:
        fprintf(out,
            ",\"old_uid\":%u,\"new_uid\":%u,\"old_gid\":%u,\"new_gid\":%u",
            e->data.principal.old_uid, e->data.principal.new_uid,
            e->data.principal.old_gid, e->data.principal.new_gid);
        break;
    case EVENT_INJECT_PTRACE:
    case EVENT_INJECT_VM_WRITE: {
        /* target process's subject uuid: best-effort using its current
         * start time from cache; if we've never seen it, fall back to
         * pid-only hashing so the edge still resolves to *something*. */
        uint64_t target_start = pid_cache[e->data.inject.target_pid % PID_CACHE_SIZE].used
            ? pid_cache[e->data.inject.target_pid % PID_CACHE_SIZE].start_ns
            : 0;
        uint64_t target_subj = subject_uuid(e->data.inject.target_pid, target_start);
        fprintf(out,
            ",\"object_uuid\":\"%016llx\",\"object_type\":\"Subject\","
            "\"target_pid\":%u,\"ptrace_request\":%u",
            (unsigned long long)target_subj,
            e->data.inject.target_pid, e->data.inject.request);
        break;
    }
    case EVENT_CLONE:
        fprintf(out, ",\"child_pid\":%u", e->data.inject.target_pid);
        break;
    case EVENT_EXECUTE:
        fprintf(out, ",\"argv\":\"%s\"", e->data.exec.argv);
        break;
    default:
        break;
    }

    fprintf(out, "}\n");
    fflush(out);
    return 0;
}

int main(int argc, char **argv)
{
    struct collector_bpf *skel;
    struct ring_buffer *rb = NULL;
    int err;

    out = stdout;
    for (int i = 1; i < argc; i++) {
        if (strcmp(argv[i], "-o") == 0 && i + 1 < argc) {
            out = fopen(argv[i + 1], "a");
            if (!out) {
                perror("fopen");
                return 1;
            }
        }
    }

    signal(SIGINT, handle_sigint);
    signal(SIGTERM, handle_sigint);

    libbpf_set_strict_mode(LIBBPF_STRICT_ALL);

    skel = collector_bpf__open_and_load();
    if (!skel) {
        fprintf(stderr, "failed to open/load BPF skeleton\n");
        return 1;
    }

    err = collector_bpf__attach(skel);
    if (err) {
        fprintf(stderr, "failed to attach BPF programs: %d\n", err);
        goto cleanup;
    }

    rb = ring_buffer__new(bpf_map__fd(skel->maps.events),
                           handle_event, NULL, NULL);
    if (!rb) {
        fprintf(stderr, "failed to create ring buffer\n");
        err = -1;
        goto cleanup;
    }

    fprintf(stderr, "[collector] attached, streaming JSONL to %s\n",
            out == stdout ? "stdout" : "file");

    while (running) {
        err = ring_buffer__poll(rb, 100 /* ms */);
        if (err == -EINTR) {
            err = 0;
            break;
        }
        if (err < 0) {
            fprintf(stderr, "ring_buffer__poll error: %d\n", err);
            break;
        }
    }

cleanup:
    ring_buffer__free(rb);
    collector_bpf__destroy(skel);
    if (out != stdout)
        fclose(out);
    return err < 0 ? 1 : 0;
}
