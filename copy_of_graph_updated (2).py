with gzip.open(INPUT_FILE, "rb") as f:

    avro = reader(
        f,
        handle_unicode_errors="replace"
    )

    for record in avro:

        records += 1

        
        datum = record.get("datum")

        if not isinstance(datum, dict):
            continue

        event_type = datum.get("type")
        timestamp = datum.get("timestampNanos")
        subject = datum.get("subject")
        obj = datum.get("predicateObject")

        if (
            event_type is None
            or timestamp is None
            or subject is None
            or obj is None
        ):
            continue

        timestamp = int(timestamp)

        if timestamp < START_NS or timestamp >= END_NS:
            continue

        if isinstance(subject, bytes):
            subject = subject.hex()

        if isinstance(obj, bytes):
            obj = obj.hex()

        
        if not subject or not obj:
            continue

        window_id = int(
            (timestamp - START_NS)
            / 10_000_000_000
        )

        if window_id < 0 or window_id >= 72:
            continue

        window = windows[window_id]

        # ----------------------------------------------------
        # Process node
        # ----------------------------------------------------

        if subject not in window["nodes"]:

            window["nodes"][subject] = {
                "type": "process",
                "events": [0] * 13
            }

        # ----------------------------------------------------
        # File / socket node
        # ----------------------------------------------------

        node_type = (
            "socket"
            if event_type in NETWORK_EVENTS
            else "file"
        )

        if obj not in window["nodes"]:

            window["nodes"][obj] = {
                "type": node_type,
                "events": [0] * 13
            }

        # ----------------------------------------------------
        # Count event
        # ----------------------------------------------------

        if event_type in EVENT_INDEX:

            feature_id = EVENT_INDEX[event_type]

            window["nodes"][subject]["events"][feature_id] += 1


        window["edges"].append(
            (subject, obj)
        )

        events_kept += 1

       

        if records % 1_000_000 == 0:

            print(
                f"Records scanned: {records:,}"
            )


